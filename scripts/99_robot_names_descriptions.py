def main() -> int:
    store = RobotStore()
    store.init_db()
    changed = 0
    for iid, (name, description) in NAMES.items():
        row = store.get_instance(iid)
        if row is None:
            print(f"нет робота {iid} — пропущен")
            continue
        if row["note"] == name and row.get("description") == description:
            continue
        with store._conn() as c:
            c.execute(
                "UPDATE instances SET note=?, description=? WHERE id=?",
                (name, description, iid))
            store._event(c, iid, "rename", row,
                         {**row, "note": name, "description": description},
                         "простые имена и описания идеи", "script", _now())
        changed += 1
        print(f"{iid}: {name}")
    print(f"обновлено {changed} из {len(NAMES)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
